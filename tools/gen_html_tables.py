"""crates/osiris-hash/src/html/tables.rs üretici (R4).

`content_hash` HTML soyma adımı (docs/SOZLESME.md §1) bs4 4.15 + html.parser ile birebir
olmalıdır. Davranışı belirleyen sabit tablolar (adlandırılmış entity'ler, Windows-1252
yeniden eşlemesi, boş öğeler, dize kapları) bs4'ün kendisinden okunur; elle kopyalanmaz.

    python tools/gen_html_tables.py          # dosyayı yeniden yazar
    python tools/gen_html_tables.py --check  # fark varsa çıkış kodu 1
"""

from __future__ import annotations

import html as _html
import sys
from html.entities import html5 as _HTML5
from pathlib import Path

import bs4
from bs4.builder import HTMLTreeBuilder
from bs4.builder._htmlparser import HTMLParserTreeBuilder
from bs4.dammit import EntitySubstitution, UnicodeDammit

OUT = Path(__file__).resolve().parents[1] / "crates/osiris-hash/src/html/tables.rs"


def _lit(s: str) -> str:
    out = []
    for ch in s:
        if ch in '"\\' or not ch.isprintable() or ord(ch) > 0x7E:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def render() -> str:
    builder = HTMLParserTreeBuilder()
    entities = sorted(EntitySubstitution.HTML_ENTITY_TO_CHARACTER.items())
    # numeric_character_reference tabloyu yalnızca 0x80–0x9F için kullanır
    win = sorted((k, v) for k, v in UnicodeDammit.WINDOWS_1252_TO_UTF8.items() if 0x80 <= k <= 0x9F)
    lines = [
        "// @generated by tools/gen_html_tables.py — elle düzenlemeyin.",
        f"// Kaynak: beautifulsoup4 {bs4.__version__}",
        "",
        "/// bs4 `EntitySubstitution.HTML_ENTITY_TO_CHARACTER` (ada göre sıralı; ikili arama).",
        "pub static ENTITIES: &[(&str, &str)] = &[",
        *[f"    ({_lit(k)}, {_lit(v)})," for k, v in entities],
        "];",
        "",
        "/// bs4 `UnicodeDammit.WINDOWS_1252_TO_UTF8` (0x80–0x9F sayısal referansları).",
        "pub static WINDOWS_1252: &[(u32, &str)] = &[",
        *[f"    (0x{k:x}, {_lit(v.decode('utf-8'))})," for k, v in win],
        "];",
        "",
        "/// bs4 `UnicodeDammit.ENUMERATED_NONCHARACTERS`.",
        "pub static NONCHARACTERS: &[u32] = &[",
        *[f"    0x{c:x}," for c in sorted(UnicodeDammit.ENUMERATED_NONCHARACTERS)],
        "];",
        "",
        "/// `HTMLTreeBuilder.DEFAULT_EMPTY_ELEMENT_TAGS` (boş öğeler hemen kapanır).",
        "pub static EMPTY_ELEMENT_TAGS: &[&str] = &[",
        *[f"    {_lit(t)}," for t in sorted(builder.empty_element_tags)],
        "];",
        "",
        "/// Python `html.entities.html5` (`;` dahil adlar; ikili arama) — `html.unescape` için.",
        "pub static HTML5: &[(&str, &str)] = &[",
        *[f"    ({_lit(k)}, {_lit(v)})," for k, v in sorted(_HTML5.items())],
        "];",
        "",
        "/// Python `html._invalid_charrefs`.",
        "pub static INVALID_CHARREFS: &[(u32, &str)] = &[",
        *[f"    (0x{k:x}, {_lit(v)})," for k, v in sorted(_html._invalid_charrefs.items())],
        "];",
        "",
        "/// Python `html._invalid_codepoints`.",
        "pub static INVALID_CODEPOINTS: &[u32] = &[",
        *[f"    0x{c:x}," for c in sorted(_html._invalid_codepoints)],
        "];",
        "",
        "/// `HTMLTreeBuilder.DEFAULT_STRING_CONTAINERS` anahtarları — içlerindeki metin",
        "/// `get_text()` çıktısına girmez (Script, Stylesheet, TemplateString, Ruby…).",
        "pub static STRING_CONTAINERS: &[&str] = &[",
        *[f"    {_lit(t)}," for t in sorted(HTMLTreeBuilder.DEFAULT_STRING_CONTAINERS)],
        "];",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} güncel değil: python tools/gen_html_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"yazıldı: {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
