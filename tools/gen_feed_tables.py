"""crates/osiris-feed/src/feed_tables.rs üretici (R5, rss plugin'i).

Python rss plugin'i feedparser kullanır; Rust karşılığı feedparser'ın HTML temizleyici
tablolarını (izinli öğe/öznitelik, boş öğeler, URI şemaları, cp1252 çevirisi) feedparser'ın
kendisinden alır.

    python tools/gen_feed_tables.py          # dosyayı yeniden yazar
    python tools/gen_feed_tables.py --check  # fark varsa çıkış kodu 1
"""

from __future__ import annotations

import html.entities
import sys
from pathlib import Path

import feedparser
from feedparser import mixin, urls
from feedparser.html import _BaseHTMLProcessor
from feedparser.sanitizer import _HTMLSanitizer

OUT = Path(__file__).resolve().parents[1] / "crates/osiris-feed/src/feed_tables.rs"


def _lit(s: str) -> str:
    out = []
    for ch in s:
        if ch in '"\\' or not ch.isprintable() or ord(ch) > 0x7E:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def _list(name: str, doc: str, values) -> list[str]:
    return [f"/// {doc}", f"pub static {name}: &[&str] = &[",
            *[f"    {_lit(v)}," for v in sorted(values)], "];", ""]


def render() -> str:
    cp = sorted((k if isinstance(k, int) else ord(k), v) for k, v in mixin._cp1252.items())
    lines = [
        "// @generated by tools/gen_feed_tables.py — elle düzenlemeyin.",
        f"// Kaynak: feedparser {feedparser.__version__}",
        "",
        *_list("ACCEPTABLE_ELEMENTS", "`_HTMLSanitizer.acceptable_elements`", _HTMLSanitizer.acceptable_elements),
        *_list("ACCEPTABLE_ATTRIBUTES", "`_HTMLSanitizer.acceptable_attributes`", _HTMLSanitizer.acceptable_attributes),
        *_list("UNACCEPTABLE_WITH_END_TAG", "`_HTMLSanitizer.unacceptable_elements_with_end_tag`",
               _HTMLSanitizer.unacceptable_elements_with_end_tag),
        *_list("ELEMENTS_NO_END_TAG", "`_BaseHTMLProcessor.elements_no_end_tag`", _BaseHTMLProcessor.elements_no_end_tag),
        *_list("ACCEPTABLE_URI_SCHEMES", "`urls.ACCEPTABLE_URI_SCHEMES`", urls.ACCEPTABLE_URI_SCHEMES),
        *_list("ENTITYDEFS", "`html.entities.entitydefs` adları (looks_like_html)", html.entities.entitydefs),
        "/// `mixin._cp1252` (U+0080–U+009F → windows-1252 karşılığı).",
        "pub static CP1252: &[(u32, &str)] = &[",
        *[f"    (0x{k:x}, {_lit(v)})," for k, v in cp],
        "];",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} güncel değil: python tools/gen_feed_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"yazıldı: {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
